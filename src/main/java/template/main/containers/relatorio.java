private void adicionarResumoEstatistico(Document doc, Connection con) throws Exception {
    Font sectionFont = new Font(Font.FontFamily.HELVETICA, 14, Font.BOLD, BaseColor.BLUE);
    Paragraph section = new Paragraph("RESUMO ESTATÍSTICO", sectionFont);
    section.setSpacingAfter(10);
    doc.add(section);
    
    // Obter estatísticas
    int[] estatisticas = obterEstatisticas(con);
    
    PdfPTable table = new PdfPTable(2);
    table.setWidthPercentage(100);
    table.setSpacingBefore(10);
    table.setSpacingAfter(20);
    
    // Cabeçalho
    Font headerFont = new Font(Font.FontFamily.HELVETICA, 11, Font.BOLD, BaseColor.WHITE);
    PdfPCell headerCell = new PdfPCell(new Phrase("ESTATÍSTICA", headerFont));
    headerCell.setBackgroundColor(BaseColor.DARK_GRAY);
    headerCell.setHorizontalAlignment(Element.ALIGN_CENTER);
    headerCell.setPadding(8);
    table.addCell(headerCell);
    
    headerCell = new PdfPCell(new Phrase("VALOR", headerFont));
    headerCell.setBackgroundColor(BaseColor.DARK_GRAY);
    headerCell.setHorizontalAlignment(Element.ALIGN_CENTER);
    headerCell.setPadding(8);
    table.addCell(headerCell);
    
    // Dados - AGORA COM 7 ITENS
    Font dataFont = new Font(Font.FontFamily.HELVETICA, 10);
    String[] labels = {
        "Total de Utilizadores",
        "Total de Editoras",
        "Total de Obras", 
        "Total de Exemplares",
        "Empréstimos Ativos",
        "Reservas Ativas",
        "Multas em Aberto (Kz)"  // ← AGORA SÃO 7 ITENS
    };
    
    for (int i = 0; i < labels.length; i++) {
        PdfPCell labelCell = new PdfPCell(new Phrase(labels[i], dataFont));
        labelCell.setPadding(5);
        table.addCell(labelCell);
        
        String value;
        if (i == 6) { // Multas (agora posição 6)
            value = String.format("%,.2f", (double) estatisticas[i]);
        } else {
            value = String.valueOf(estatisticas[i]);
        }
        
        PdfPCell valueCell = new PdfPCell(new Phrase(value, dataFont));
        valueCell.setHorizontalAlignment(Element.ALIGN_CENTER);
        valueCell.setPadding(5);
        table.addCell(valueCell);
    }
    
    doc.add(table);
}

private int[] obterEstatisticas(Connection con) throws SQLException {
    // CORREÇÃO: Agora array com tamanho 7
    int[] stats = new int[7]; // Índices: 0,1,2,3,4,5,6
    
    String[] queries = {
        "SELECT COUNT(*) FROM Utilizador",
        "SELECT COUNT(*) FROM Editora",
        "SELECT COUNT(*) FROM Obra",
        "SELECT COUNT(*) FROM Exemplar",
        "SELECT COUNT(*) FROM Emprestimo WHERE estado = 'ABERTO'",
        "SELECT COUNT(*) FROM Reserva WHERE status = 'ATIVA'",
        "SELECT COALESCE(SUM(valor), 0) FROM Multa WHERE pago = false"
    };
    
    Statement stmt = con.createStatement();
    for (int i = 0; i < queries.length; i++) {
        ResultSet rs = stmt.executeQuery(queries[i]);
        if (rs.next()) {
            // CORREÇÃO: Cast para double apenas na última query
            stats[i] = i == 6 ? (int) rs.getDouble(1) : rs.getInt(1);
        }
        rs.close();
    }
    stmt.close();
    
    return stats;
}



private void adicionarTabela(Document doc, Connection con, String titulo, 
                            String sql, String[] colunas, float[] larguras) throws Exception {
    
    // Título da seção
    Font sectionFont = new Font(Font.FontFamily.HELVETICA, 14, Font.BOLD, BaseColor.BLUE);
    Paragraph section = new Paragraph(titulo, sectionFont);
    section.setSpacingBefore(20);
    section.setSpacingAfter(10);
    doc.add(section);
    
    // Criar tabela
    PdfPTable table = new PdfPTable(colunas.length);
    table.setWidthPercentage(100);
    if (larguras != null) {
        table.setWidths(larguras);
    }
    
    // Cabeçalho
    Font headerFont = new Font(Font.FontFamily.HELVETICA, 10, Font.BOLD, BaseColor.WHITE);
    for (String coluna : colunas) {
        PdfPCell cell = new PdfPCell(new Phrase(coluna, headerFont));
        cell.setBackgroundColor(BaseColor.DARK_GRAY);
        cell.setHorizontalAlignment(Element.ALIGN_CENTER);
        cell.setPadding(5);
        table.addCell(cell);
    }
    
    // Dados
    Font dataFont = new Font(Font.FontFamily.HELVETICA, 9);
    Statement stmt = con.createStatement();
    ResultSet rs = stmt.executeQuery(sql);
    
    int rowCount = 0;
    while (rs.next() && rowCount < 100) { // Limita a 100 linhas por tabela
        for (int i = 1; i <= colunas.length; i++) {
            String valor = rs.getString(i);
            if (valor == null) valor = "-";
            
            PdfPCell cell = new PdfPCell(new Phrase(valor, dataFont));
            cell.setPadding(4);
            
            // Colorir células especiais
            if (colunas[i-1].equals("Estado")) {
                cell.setBackgroundColor(corPorEstado(valor));
            } else if (colunas[i-1].equals("Perfil")) {
                cell.setBackgroundColor(corPorPerfil(valor));
            }
            
            table.addCell(cell);
        }
        rowCount++;
    }
    
    if (rowCount == 0) {
        PdfPCell emptyCell = new PdfPCell(new Phrase("Nenhum registro encontrado", dataFont));
        emptyCell.setColspan(colunas.length);
        emptyCell.setHorizontalAlignment(Element.ALIGN_CENTER);
        table.addCell(emptyCell);
    }
    
    rs.close();
    stmt.close();
    doc.add(table);
    
    // Nota se atingiu limite
    if (rowCount >= 100) {
        Font notaFont = new Font(Font.FontFamily.HELVETICA, 8, Font.ITALIC, BaseColor.GRAY);
        Paragraph nota = new Paragraph("* Mostrando apenas os primeiros 100 registros", notaFont);
        doc.add(nota);
    }
}

private void adicionarTabelaComTotal(Document doc, Connection con, String titulo,
                                    String sql, String[] colunas, float[] larguras,
                                    String colunaSoma) throws Exception {
    
    // Primeiro obtém os dados e calcula total
    Statement stmt = con.createStatement();
    ResultSet rs = stmt.executeQuery(sql.replace("SELECT", "SELECT SQL_CALC_FOUND_ROWS"));
    
    double total = 0;
    int rowCount = 0;
    
    // Contar linhas e calcular total
    Statement stmtCount = con.createStatement();
    ResultSet rsCount = stmtCount.executeQuery("SELECT FOUND_ROWS()");
    if (rsCount.next()) {
        rowCount = rsCount.getInt(1);
    }
    rsCount.close();
    stmtCount.close();
    
    // Título da seção
    Font sectionFont = new Font(Font.FontFamily.HELVETICA, 14, Font.BOLD, BaseColor.BLUE);
    Paragraph section = new Paragraph(titulo, sectionFont);
    section.setSpacingBefore(20);
    section.setSpacingAfter(10);
    doc.add(section);
    
    // Criar tabela
    PdfPTable table = new PdfPTable(colunas.length);
    table.setWidthPercentage(100);
    if (larguras != null) {
        table.setWidths(larguras);
    }
    
    // Cabeçalho
    Font headerFont = new Font(Font.FontFamily.HELVETICA, 10, Font.BOLD, BaseColor.WHITE);
    for (String coluna : colunas) {
        PdfPCell cell = new PdfPCell(new Phrase(coluna, headerFont));
        cell.setBackgroundColor(BaseColor.DARK_GRAY);
        cell.setHorizontalAlignment(Element.ALIGN_CENTER);
        cell.setPadding(5);
        table.addCell(cell);
    }
    
    // Dados
    Font dataFont = new Font(Font.FontFamily.HELVETICA, 9);
    int colunaValorIndex = -1;
    for (int i = 0; i < colunas.length; i++) {
        if (colunas[i].contains("Valor")) {
            colunaValorIndex = i + 1;
            break;
        }
    }
    
    rs = stmt.executeQuery(sql); // Executa novamente para obter dados
    int rowsAdded = 0;
    
    while (rs.next() && rowsAdded < 100) {
        for (int i = 1; i <= colunas.length; i++) {
            String valor = rs.getString(i);
            if (valor == null) valor = "-";
            
            PdfPCell cell = new PdfPCell(new Phrase(valor, dataFont));
            cell.setPadding(4);
            
            // Somar valores se for coluna de valor
            if (i == colunaValorIndex && !valor.equals("-")) {
                try {
                    total += Double.parseDouble(valor);
                    cell.setBackgroundColor(BaseColor.LIGHT_GRAY);
                } catch (NumberFormatException e) {
                    // Ignora se não for número
                }
            }
            
            table.addCell(cell);
        }
        rowsAdded++;
    }
    
    // Adicionar linha de total
    if (rowsAdded > 0 && colunaValorIndex > 0) {
        PdfPCell totalLabel = new PdfPCell(new Phrase("TOTAL EM ABERTO:", 
            new Font(Font.FontFamily.HELVETICA, 10, Font.BOLD)));
        totalLabel.setColspan(colunaValorIndex - 1);
        totalLabel.setHorizontalAlignment(Element.ALIGN_RIGHT);
        totalLabel.setPadding(5);
        table.addCell(totalLabel);
        
        PdfPCell totalCell = new PdfPCell(new Phrase(String.format("%,.2f Kz", total),
            new Font(Font.FontFamily.HELVETICA, 10, Font.BOLD, BaseColor.RED)));
        totalCell.setColspan(colunas.length - colunaValorIndex + 1);
        totalCell.setBackgroundColor(new BaseColor(255, 240, 240));
        totalCell.setHorizontalAlignment(Element.ALIGN_CENTER);
        totalCell.setPadding(5);
        table.addCell(totalCell);
    }
    
    rs.close();
    stmt.close();
    doc.add(table);
}

// Métodos auxiliares para cores
private BaseColor corPorEstado(String estado) {
    if (estado == null) return BaseColor.WHITE;
    switch(estado.toUpperCase()) {
        case "ATIVO": return new BaseColor(200, 255, 200);
        case "INATIVO": return new BaseColor(255, 200, 200);
        case "BLOQUEADO": return new BaseColor(255, 220, 150);
        default: return BaseColor.WHITE;
    }
}

private BaseColor corPorPerfil(String perfil) {
    if (perfil == null) return BaseColor.WHITE;
    switch(perfil.toUpperCase()) {
        case "ADMIN": return new BaseColor(255, 200, 200);
        case "BIBLIO": return new BaseColor(200, 255, 200);
        case "LEITOR": return new BaseColor(200, 200, 255);
        default: return BaseColor.WHITE;
    }
}

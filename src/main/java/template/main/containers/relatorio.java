public void gerarRelatorioPDFCompleto() {
    Document doc = new Document(PageSize.A4.rotate()); // Paisagem para mais colunas
    doc.setMargins(20, 20, 20, 20);
    
    try {
        // Criar PDF
        PdfWriter.getInstance(doc, new FileOutputStream("Relatorio_SGBU_Completo.pdf"));
        doc.open();
        
        // Conexão com banco
        Connection con = Database.getConnection();
        
        // ========== CABEÇALHO ==========
        Font tituloFont = new Font(Font.FontFamily.HELVETICA, 18, Font.BOLD, BaseColor.DARK_GRAY);
        Paragraph titulo = new Paragraph("RELATÓRIO COMPLETO - SISTEMA SGBU", tituloFont);
        titulo.setAlignment(Element.ALIGN_CENTER);
        titulo.setSpacingAfter(10);
        doc.add(titulo);
        
        Font subtituloFont = new Font(Font.FontFamily.HELVETICA, 12, Font.NORMAL, BaseColor.GRAY);
        Paragraph subtitulo = new Paragraph("Gerado em: " + new SimpleDateFormat("dd/MM/yyyy HH:mm").format(new Date()), subtituloFont);
        subtitulo.setAlignment(Element.ALIGN_CENTER);
        subtitulo.setSpacingAfter(20);
        doc.add(subtitulo);
        
        doc.add(new Chunk("\n"));
        doc.add(new LineSeparator());
        doc.add(new Chunk("\n"));
        
        // ========== RESUMO ESTATÍSTICO ==========
        adicionarResumoEstatistico(doc, con);
        
        // ========== TABELA DE UTILIZADORES ==========
        adicionarTabela(doc, con, "UTILIZADORES", 
            "SELECT nomeCompleto, email, perfil, estado, " +
            "DATE_FORMAT(dataRegisto, '%d/%m/%Y') as dataReg " +
            "FROM Utilizador ORDER BY perfil, nomeCompleto",
            new String[]{"Nome", "Email", "Perfil", "Estado", "Data Registo"},
            new float[]{3f, 3f, 1.5f, 1.5f, 1.5f}
        );
        
        // ========== TABELA DE EDITORAS ==========
        // CORREÇÃO: Mudou Morada para Endereço e removeu dataRegisto
        adicionarTabela(doc, con, "EDITORAS CADASTRADAS",
            "SELECT nome, endereco, telefone, email " +  // Removido: , DATE_FORMAT(dataRegisto, '%d/%m/%Y') as dataRegistro
            "FROM Editora ORDER BY nome",
            new String[]{"Nome", "Endereço", "Telefone", "Email"}, // Morada → Endereço
            new float[]{2f, 3f, 1.5f, 2f} // Ajustado larguras
        );
        
        // ========== TABELA DE OBRAS ==========
        adicionarTabela(doc, con, "CATÁLOGO DE OBRAS",
            "SELECT titulo, isbn, ano, edicao, idioma, " +
            "(SELECT COUNT(*) FROM Exemplar e WHERE e.obraId = o.id) as totalExemplares " +
            "FROM Obra o ORDER BY titulo",
            new String[]{"Título", "ISBN", "Ano", "Edição", "Idioma", "Exemplares"},
            new float[]{4f, 2f, 0.8f, 1.2f, 1f, 1f}
        );
        
        // ========== TABELA DE EXEMPLARES ==========
        adicionarTabela(doc, con, "EXEMPLARES - ESTADO ATUAL",
            "SELECT e.codigoBarras, e.cota, e.estado, o.titulo, " +
            "DATE_FORMAT(FROM_UNIXTIME(e.aquisicaoData/1000), '%d/%m/%Y') as dataAquisicao " +
            "FROM Exemplar e " +
            "JOIN Obra o ON e.obraId = o.id " +
            "ORDER BY e.estado, e.codigoBarras",
            new String[]{"Código Barras", "Cota", "Estado", "Obra", "Aquisição"},
            new float[]{1.5f, 1.5f, 1.2f, 3f, 1.3f}
        );
        
        // ========== TABELA DE EMPRÉSTIMOS ATIVOS ==========
        adicionarTabela(doc, con, "EMPRÉSTIMOS",
            "SELECT u.nomeCompleto, o.titulo, ex.codigoBarras, " +
            "DATE_FORMAT(FROM_UNIXTIME(e.dataEmprestimo/1000), '%d/%m/%Y') as dataEmp, " +
            "DATE_FORMAT(FROM_UNIXTIME(e.dataPrevistaDevolucao/1000), '%d/%m/%Y') as dataPrev " +
            "FROM Emprestimo e " +
            "JOIN Utilizador u ON e.utilizadorId = u.id " +
            "JOIN Exemplar ex ON e.exemplarId = ex.id " +
            "JOIN Obra o ON ex.obraId = o.id " +
            "WHERE e.estado = 'ABERTO' " +
            "ORDER BY e.dataPrevistaDevolucao",
            new String[]{"Utilizador", "Obra", "Código", "Data Emp", "Data Prev"},
            new float[]{2.5f, 3f, 1.5f, 1.5f, 1.5f}
        );
        
        // ========== TABELA DE RESERVAS ==========
        adicionarTabela(doc, con, "RESERVAS",
            "SELECT u.nomeCompleto, o.titulo, r.posicaoFila, " +
            "DATE_FORMAT(FROM_UNIXTIME(r.dataReserva/1000), '%d/%m/%Y') as dataReserva " +
            "FROM Reserva r " +
            "JOIN Utilizador u ON r.utilizadorId = u.id " +
            "JOIN Obra o ON r.obraId = o.id " +
            "WHERE r.status = 'ATIVA' " +
            "ORDER BY r.posicaoFila",
            new String[]{"Utilizador", "Obra", "Posição", "Data Reserva"},
            new float[]{3f, 3f, 1f, 1.5f}
        );
        
        // ========== TABELA DE MULTAS EM ABERTO ==========
        adicionarTabelaComTotal(doc, con, "MULTAS EM ABERTO",
            "SELECT u.nomeCompleto, m.valor, m.motivo, o.titulo, " +
            "DATE_FORMAT(FROM_UNIXTIME(m.dataGeracao/1000), '%d/%m/%Y') as dataGeracao " +
            "FROM Multa m " +
            "JOIN Emprestimo e ON m.emprestimoId = e.id " +
            "JOIN Exemplar ex ON e.exemplarId = ex.id " +
            "JOIN Obra o ON ex.obraId = o.id " +
            "JOIN Utilizador u ON e.utilizadorId = u.id " +
            "WHERE m.pago = false " +
            "ORDER BY m.valor DESC",
            new String[]{"Utilizador", "Valor (Kz)", "Motivo", "Obra", "Data Geração"},
            new float[]{2.5f, 1.5f, 1.5f, 2.5f, 1.5f},
            "valor" // Coluna para somar
        );
        
        // ========== RODAPÉ ==========
        doc.add(new Chunk("\n\n"));
        doc.add(new LineSeparator());
        
        Font rodapeFont = new Font(Font.FontFamily.HELVETICA, 9, Font.ITALIC, BaseColor.GRAY);
        Paragraph rodape = new Paragraph(
            "Relatório gerado automaticamente pelo Sistema de Gestão de Biblioteca Universitária (SGBU)\n",
            rodapeFont
        );
        rodape.setAlignment(Element.ALIGN_CENTER);
        doc.add(rodape);
        
        // Fechar conexão
        con.close();
        
    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(null, 
            "Erro ao gerar relatório: " + e.getMessage(), 
            "Erro", 
            JOptionPane.ERROR_MESSAGE);
    } finally {
        doc.close();
    }
    
    // Abrir PDF automaticamente
    try {
        Desktop.getDesktop().open(new File("Relatorio_SGBU_Completo.pdf"));
    } catch (Exception e) {
        e.printStackTrace();
    }
}

